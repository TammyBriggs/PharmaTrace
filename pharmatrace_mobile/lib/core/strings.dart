/// Lets widgets below the app root read the current language. Widgets that call [BuildContext.tr] rebuild
/// when the language changes, without restarting the app or losing the screen the person is on.
class LanguageScope extends InheritedWidget {
  final AppLanguage language;

  const LanguageScope({super.key, required this.language, required super.child});

  @override
  bool updateShouldNotify(LanguageScope oldWidget) => language != oldWidget.language;
}

extension TranslateContext on BuildContext {
  /// The text for [key] in the current language. Placeholders such as {name} are filled from [vars].
  String tr(String key, [Map<String, Object?> vars = const {}]) {
    final scope = dependOnInheritedWidgetOfExactType<LanguageScope>();
    return translate(scope?.language ?? LanguageController().language, key, vars);
  }
}

/// Kinyarwanda text for [key], or the English text when no translation exists yet (or the key is unknown).
String translate(AppLanguage language, String key, [Map<String, Object?> vars = const {}]) {
  final text = (language == AppLanguage.rw ? _rw[key] : null) ?? _en[key] ?? key;
  if (vars.isEmpty) return text;
  var out = text;
  vars.forEach((name, value) => out = out.replaceAll('{$name}', '${value ?? ''}'));
  return out;
}

